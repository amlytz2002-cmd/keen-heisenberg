// Utility functions for easy access
export const getAllTier1Lessons = (): MicroLesson[] => {
  return MEDICINAL_CHEMISTRY_TIER_1.flatMap((m) => m.lessons);
};

export const getLessonById = (lessonId: string): MicroLesson | undefined => {
  return getAllTier1Lessons().find((l) => l.id === lessonId);
};

export const getModuleByLessonId = (lessonId: string): CourseModule | undefined => {
  return MEDICINAL_CHEMISTRY_TIER_1.find((m) => m.lessons.some((l) => l.id === lessonId));
};

export const getNextLesson = (currentLessonId: string): MicroLesson | undefined => {
  const allLessons = getAllTier1Lessons();
  const currentIndex = allLessons.findIndex((l) => l.id === currentLessonId);
  if (currentIndex >= 0 && currentIndex < allLessons.length - 1) {
    return allLessons[currentIndex + 1];
  }
  return undefined;
};
